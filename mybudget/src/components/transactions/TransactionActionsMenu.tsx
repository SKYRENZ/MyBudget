"use client";

import { useEffect, useRef, useState } from "react";
import type { Transaction } from "@/lib/database-types";

/** Returns true if the transaction is within the 7-day edit window */
export function isTransactionEditable(transaction: Transaction): boolean {
  const created = new Date(transaction.created_at);
  const now = new Date();
  const diffMs = now.getTime() - created.getTime();
  const diffDays = diffMs / (1000 * 60 * 60 * 24);
  return diffDays <= 7;
}

/** Formats the remaining editable time as a friendly string */
export function getEditableTimeLabel(transaction: Transaction): string {
  const created = new Date(transaction.created_at);
  const expiresAt = new Date(created.getTime() + 7 * 24 * 60 * 60 * 1000);
  const now = new Date();
  const diffMs = expiresAt.getTime() - now.getTime();
  const diffHours = Math.max(0, Math.floor(diffMs / (1000 * 60 * 60)));
  if (diffHours < 1) return "< 1 hour left";
  if (diffHours < 24) return `${diffHours}h left`;
  const diffDays = Math.floor(diffHours / 24);
  return `${diffDays}d left`;
}

type Props = {
  transaction: Transaction;
  onEdit: (tx: Transaction) => void;
  onDelete: (tx: Transaction) => void;
  onCreateRecurring: (tx: Transaction) => void;
};

export function TransactionActionsMenu({
  transaction,
  onEdit,
  onDelete,
  onCreateRecurring,
}: Props) {
  const [open, setOpen] = useState(false);
  const menuRef = useRef<HTMLDivElement>(null);
  const editable = isTransactionEditable(transaction);
  const isRecurring = !!transaction.recurring_transaction_id;
  const isAutoGenerated = transaction.is_auto_generated;

  // Close on outside click / Escape
  useEffect(() => {
    if (!open) return;
    function handleClick(e: MouseEvent) {
      if (menuRef.current && !menuRef.current.contains(e.target as Node)) {
        setOpen(false);
      }
    }
    function handleKey(e: KeyboardEvent) {
      if (e.key === "Escape") setOpen(false);
    }
    document.addEventListener("mousedown", handleClick);
    document.addEventListener("keydown", handleKey);
    return () => {
      document.removeEventListener("mousedown", handleClick);
      document.removeEventListener("keydown", handleKey);
    };
  }, [open]);

  return (
    <div ref={menuRef} className="relative shrink-0">
      <button
        type="button"
        onClick={(e) => { e.stopPropagation(); setOpen((v) => !v); }}
        aria-label="Transaction actions"
        className="grid size-8 place-items-center rounded text-ink-soft opacity-100 transition-opacity hover:bg-ink/8 hover:text-ink focus-visible:opacity-100 md:opacity-0 md:group-hover:opacity-100 dark:hover:bg-white/10 dark:hover:text-white"
        style={{ opacity: open ? 1 : undefined }}
      >
        ⋮
      </button>

      {open && (
        <div
          className="fixed inset-x-0 bottom-0 z-70 border-t border-ink/15 bg-paper p-2 pb-[calc(1rem+env(safe-area-inset-bottom))] shadow-[0_-10px_30px_rgba(0,0,0,0.18)] md:absolute md:inset-auto md:right-0 md:top-full md:z-50 md:mt-1 md:min-w-[220px] md:border md:p-0 md:py-1 md:shadow-lg dark:border-white/10 dark:bg-[#1e1812]"
          role="menu"
        >
          {/* Status badges */}
          {(isRecurring || isAutoGenerated) && (
            <div className="border-b border-ink/10 px-3 py-1.5 dark:border-white/10">
              {isRecurring && (
                <span className="inline-flex items-center gap-1 text-[0.6rem] font-bold uppercase tracking-[0.1em] text-blue-600 dark:text-blue-400">
                  🔁 Recurring
                </span>
              )}
              {isAutoGenerated && (
                <span className="ml-2 inline-flex items-center gap-1 text-[0.6rem] font-bold uppercase tracking-[0.1em] text-purple-600 dark:text-purple-400">
                  Auto-generated
                </span>
              )}
            </div>
          )}

          {/* Edit or View Details */}
          <button
            type="button"
            role="menuitem"
            onClick={() => { setOpen(false); onEdit(transaction); }}
            className="flex w-full items-center gap-2.5 px-3 py-2.5 text-left text-sm transition-colors hover:bg-ink/5 md:py-2 dark:hover:bg-white/8"
          >
            <span>{editable ? "✏️" : "👁️"}</span>
            <span className="flex-1">{editable ? "Edit transaction" : "View details"}</span>
            {editable && (
              <span className="text-[0.6rem] text-ink-soft dark:text-[#cfc2af]">
                {getEditableTimeLabel(transaction)}
              </span>
            )}
          </button>

          {/* Delete */}
          <button
            type="button"
            role="menuitem"
            disabled={!editable}
            onClick={() => { setOpen(false); onDelete(transaction); }}
            className="flex w-full items-center gap-2.5 px-3 py-2 text-left text-sm text-red-700 transition-colors hover:bg-red-50 disabled:cursor-not-allowed disabled:opacity-40 dark:text-red-400 dark:hover:bg-red-900/20"
          >
            <span>🗑️</span>
            <span>Delete transaction</span>
          </button>

          <div className="my-1 border-t border-ink/10 dark:border-white/10" />

          {/* Create Recurring */}
          <button
            type="button"
            role="menuitem"
            onClick={() => { setOpen(false); onCreateRecurring(transaction); }}
            className="flex w-full items-center gap-2.5 px-3 py-2 text-left text-sm transition-colors hover:bg-ink/5 dark:hover:bg-white/8"
          >
            <span>🔁</span>
            <span>Create recurring</span>
          </button>

          {/* Lock notice */}
          {!editable && (
            <div className="border-t border-ink/10 px-3 py-2 dark:border-white/10">
              <p className="text-[0.62rem] text-ink-soft dark:text-[#cfc2af]">
                🔒 Locked — older than 7 days
              </p>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
